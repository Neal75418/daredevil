/// 月營收總覽的低基期識別參數(2026-08-13)。
///
/// 「單月年增極端 + 累計年增平庸」= 基期效應/一次性認列的定義本身
/// (實例:聯上 2026-07 單月 +1,096,390%——去年同月 53 萬 vs 今年
/// 5.8 億,建設交屋認列;同支 API 的累計年增就平庸)。用兩個資料點的
/// **關係**識別而非絕對門檻,不裁列(2026-08-05「清單完整」定稿),
/// UI 淡化+標記。
abstract final class RevenueOverviewParams {
  /// 單月年增至少要到此值(%)才可能被標低基期。
  ///
  /// 100 = 單月至少翻倍——低於翻倍的成長沒有「爆量假象」可言,
  /// 不值得動用標記(誤傷正常成長股的代價高於漏標)。
  static const double lowBaseMinYoyPct = 100;

  /// 單月年增須達累計年增的多少倍才算「背離」。
  ///
  /// 5 = 單月增速是全年趨勢的 5 倍以上——真主升段的單月與累計會同步
  /// 走高(150%/140% 這種形狀不觸發),只有一次性認列才會出現
  /// 單月 +300% 而累計 +40% 的裂口。
  static const double lowBaseDivergenceRatio = 5;
}
