  };

  /// 依 TWSE 產業別代碼取 canonical 名稱；未知代碼回 null（呼叫端 fallback
  /// FinMind 分類）。
  static String? nameForTwseCode(String code) {
    final name = _twseIndustryCodes[code];
    return name == null ? null : normalize(name);
  }
}
