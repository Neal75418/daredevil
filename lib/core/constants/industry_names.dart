    '金融業': '金融保險',
  };

  /// 正規化產業名稱，若不在對照表中則原值回傳
  static String normalize(String raw) => _normalizationMap[raw] ?? raw;

  /// TWSE 官方產業別代碼（t187ap03_L）→ 產業名稱。
